# ── §4.2 Pronunciation dictionary ─────────────────────────

REQUIRED = [
    ("Er,Cr:YSGG",    "erbium chromium Y-S-G-G"),
    ("Er:YAG",        "erbium YAG"),
    ("Nd:YAG",        "neodymium YAG"),
    ("NaOCl",         "sodium hypochlorite"),
    ("EDTA",          "E-D-T-A"),
    ("PIPS",          "pips"),
    ("µm",            "microns"),
    ("MTA",           "M-T-A"),
]


@pytest.mark.parametrize("term,say", REQUIRED)
def test_required_terms_are_substituted(term, say):
    out = apply_pronunciation(f"The {term} protocol.")
    assert say in out
    assert term not in out


def test_apexification_is_respelled_and_keeps_its_capital():
    assert apply_pronunciation("apexification") != "apexification"
    # Sentence-initial capital survives; the engine must not be handed "Ay" as
    # a separate token from a lower-case respelling.
    assert apply_pronunciation("Apexification works.")[0].isupper()


def test_the_three_laser_names_survive_each_other():
    """Er,Cr:YSGG next to Er:YAG — the hybrid §4.2 warns about.

    Pins the combination, not the mechanism: the two ordering tests below cover
    that. This one fails if anyone edits the laser entries themselves.
    """
    out = apply_pronunciation("Er,Cr:YSGG and Er:YAG and Nd:YAG were compared.")
    assert out == ("erbium chromium Y-S-G-G and erbium YAG and neodymium YAG "
                   "were compared.")
    assert "Er,Cr:" not in out


def test_a_shorter_overlapping_term_cannot_pre_empt_a_longer_one():
    """The ordering rule, exercised where it is actually load-bearing.

    Guards alone are not enough. When two terms start at the SAME character —
    which is what happens the moment someone extends the map with a shorter
    prefix like 'Er' — the longer term must win, or the laser name comes out
    half-translated as 'erbium:YAG'.
    """
    extra = [{"term": "Er", "say": "erbium"}]
    assert apply_pronunciation("Er:YAG", extra_terms=extra) == "erbium YAG"
    assert apply_pronunciation("Er,Cr:YSGG", extra_terms=extra) == \
        "erbium chromium Y-S-G-G"


def test_standalone_ysgg_still_substituted():
    """The short entry must remain reachable — it is not dead data."""
    assert apply_pronunciation("The YSGG unit") == "The Y-S-G-G unit"


@pytest.mark.parametrize("word", ["EDTAC", "PIPSY", "MTAX", "XMTA", "NaOClX"])
def test_no_substitution_inside_a_longer_word(word):
    assert apply_pronunciation(f"a {word} b") == f"a {word} b"


def test_micron_symbol_attached_to_a_number_gains_a_space():
    """'500µm' must not be spoken as 'five hundredmicrons'."""
    assert apply_pronunciation("a 500µm tip") == "a 500 microns tip"
    assert apply_pronunciation("a 500 µm tip") == "a 500 microns tip"


def test_pairs_are_ordered_longest_first():
    lengths = [len(t) for t, _ in pronunciation.pronunciation_pairs()]
    assert lengths == sorted(lengths, reverse=True)


def test_extra_terms_extend_the_map_without_mutating_it():
    before = len(pronunciation.PRONUNCIATION_TERMS)
    out = apply_pronunciation("A GentleWave cycle",
                              extra_terms=[{"term": "GentleWave", "say": "gentle wave"}])
    assert out == "A gentle wave cycle"
    assert len(pronunciation.PRONUNCIATION_TERMS) == before


