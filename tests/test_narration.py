# ── §4.5 TTS cost logging ─────────────────────────────────

def test_tts_is_priced_per_character_not_per_token(tmp_path, monkeypatch):
    import endo_ai
    log = tmp_path / "cost_log.jsonl"
    monkeypatch.setattr(endo_ai, "_COST_LOG_PATH", str(log))

    # Published rates: tts-1 $15/1M chars, tts-1-hd $30/1M chars.
    assert endo_ai.log_tts_call("t", "tts-1", 1_000_000) == pytest.approx(15.0)
    assert endo_ai.log_tts_call("t", "tts-1-hd", 1_000_000) == pytest.approx(30.0)
    assert endo_ai.log_tts_call("t", "tts-1-hd", 12_000) == pytest.approx(0.36)


def test_tts_record_is_readable_by_the_cost_aggregator(tmp_path, monkeypatch):
    """/admin/costs sums cost_usd and int()s the token fields on every row."""
    import endo_ai
    log = tmp_path / "cost_log.jsonl"
    monkeypatch.setattr(endo_ai, "_COST_LOG_PATH", str(log))
    endo_ai.log_tts_call("run_generate_audio", "tts-1-hd", 12_000,
                         mode="export", request_id="abc",
                         duration_seconds=600.0, voice="onyx")

    rec = json.loads(log.read_text(encoding="utf-8").strip())
    assert rec["kind"] == "tts"
    assert rec["characters"] == 12_000
    assert rec["input_tokens"] == 0 and rec["output_tokens"] == 0
    assert rec["model"] == "tts-1-hd" and rec["mode"] == "export"
    assert rec["voice"] == "onyx" and rec["request_id"] == "abc"
    assert rec["rate_usd_per_1m_chars"] == 30.00
    assert rec["cost_usd"] == pytest.approx(0.36)
    # Per-minute cost is the §4.5 headline number.
    assert rec["cost_usd_per_minute"] == pytest.approx(0.036)
    assert float(rec["cost_usd"]) and int(rec["input_tokens"]) == 0


