def test_chunk_timings_are_rescaled_to_the_probed_duration():
    """Measured chunk durations must be stretched onto the real file length.

    Concatenated MP3 frames do not always sum to what ffprobe reports for the
    joined file. Without the rescale the map drifts and slides advance early.
    """
    sections = [{"index": 0, "title": "A", "text": "a", "spoken": "a" * 100},
                {"index": 1, "title": "B", "text": "b", "spoken": "b" * 100}]
    chunks = [{"text": "x", "spans": [{"section": 0, "chars": 100}]},
              {"text": "y", "spans": [{"section": 1, "chars": 100}]}]
    tmap = narration.build_timestamp_map(
        "rescale-1", sections, chunks, [5.0, 5.0], total_duration=20.0,
        voice="onyx", model="tts-1-hd", backend="openai")
    slides = tmap["slides"]
    assert slides[0]["start"] == pytest.approx(0.0)
    assert slides[0]["end"] == pytest.approx(10.0), "10s of measured audio was stretched onto a 20s file"
    assert slides[1]["end"] == pytest.approx(20.0)


